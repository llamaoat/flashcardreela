#!/usr/bin/env python3
"""Builds the browser extension's shared files (extension/lib/, fonts/, icons/) from the web demo.

    python3 tools/build-extension.py

The extension (extension/) runs the web demo's engine and card renderer on TikTok, Instagram,
YouTube Shorts and X. Its own files are manifest.json, content.js, popup.html, popup.js and state.js;
everything under lib/ is copied or cut from web-demo/src/ by this script, so never edit lib/ by hand.
Run it after changing web-demo/src/ (CI checks it's up to date). Icons need Pillow.
"""
import json, pathlib, re, shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, EXT = ROOT / "web-demo" / "src", ROOT / "extension"
LIB = EXT / "lib"
LIB.mkdir(parents=True, exist_ok=True)

for name in ("engine.js", "apkg.js", "render.js", "decks.js", "notes.js"):
    shutil.copyfile(SRC / name, LIB / name)
# notes.js runs inside app.js in the web demo, where makeCard is already defined
(LIB / "notes.js").write_text("const makeCard = RC.makeCard; // defined in app.js in the web demo\n" + (SRC / "notes.js").read_text(encoding="utf-8"), encoding="utf-8")

# the card design system from head.html, plus the variables it uses, for the overlay's shadow root
head = (SRC / "head.html").read_text(encoding="utf-8")
root_vars = re.search(r":root\{(.*?)\n\}", head, re.S).group(1)
start = head.index("/* =================================================================================\n   CARD REEL DESIGN SYSTEM")
end = head.index("/* Add to Home Screen")
css = ":host{" + root_vars + "}\n" + head[start:end]
(LIB / "card-css.js").write_text("/* generated by tools/build-extension.py from web-demo/src/head.html */\nconst CARD_CSS = " +
                                 json.dumps(css, ensure_ascii=False) + ";\n", encoding="utf-8")

fonts = EXT / "fonts"
fonts.mkdir(exist_ok=True)
for f in (ROOT / "app" / "src" / "main" / "assets" / "fonts").iterdir():
    shutil.copyfile(f, fonts / f.name)

icons = EXT / "icons"
icons.mkdir(exist_ok=True)
try:
    from PIL import Image
    big = Image.open(ROOT / "docs" / "play-store" / "icon-512.png").convert("RGB")
    for n in (16, 32, 48, 128):
        big.resize((n, n), Image.LANCZOS).save(icons / ("icon-%d.png" % n), optimize=True)
except ImportError:
    print("Pillow missing: icons not rebuilt")
print("wrote", LIB.relative_to(ROOT), "fonts/ and icons/")
